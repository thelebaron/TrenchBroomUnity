std::string formatBoxes(const std::vector<vm::bbox3d>& boxes)
{
  auto parts = std::vector<std::string>{};
  parts.reserve(boxes.size());
  for (const auto& box : boxes)
  {
    parts.push_back(
      fmt::format(
        "{} {} {} {} {} {}",
        box.min.x(),
        box.min.y(),
        box.min.z(),
        box.max.x(),
        box.max.y(),
        box.max.z()));
  }
  return kdl::str_join(parts, ";");
}

Result<std::vector<vm::bbox3d>> parseBoxes(const std::string& key, const std::string& str)
{
  auto result = std::vector<vm::bbox3d>{};
  for (const auto& part : kdl::str_split(str, ";"))
  {
    auto values = std::vector<double>{};
    for (const auto& token : kdl::str_split(part, " "))
    {
      if (token.empty())
      {
        continue;
      }
      const auto value = kdl::str_to_double(token);
      if (!value)
      {
        return Error{fmt::format("Invalid number '{}' in room property {}", token, key)};
      }
      values.push_back(*value);
    }
    if (values.empty())
    {
      continue;
    }
    if (
      values.size() != 6u || values[3] < values[0] || values[4] < values[1]
      || values[5] < values[2])
    {
      return Error{fmt::format("Invalid box '{}' in room property {}", part, key)};
    }
    result.push_back(
      vm::bbox3d{{values[0], values[1], values[2]}, {values[3], values[4], values[5]}});
  }
  return result;
}

template <typename Container>
std::string propertyOrEmpty(const Container& container, const std::string& key)
{
  const auto* value = container.property(key);
  return value ? *value : std::string{};
}

template <typename Container>
Result<RoomRecipe> readRecipeFrom(const Container& container)
{
  auto spaces =
    parseBoxes(RoomKeys::Spaces, propertyOrEmpty(container, RoomKeys::Spaces));
  if (spaces.is_error())
  {
    return std::get<Error>(spaces.error());
  }
  auto doors = parseBoxes(RoomKeys::Doors, propertyOrEmpty(container, RoomKeys::Doors));
  if (doors.is_error())
  {
    return std::get<Error>(doors.error());
  }
  auto clips = parseBoxes(RoomKeys::Clips, propertyOrEmpty(container, RoomKeys::Clips));
  if (clips.is_error())
  {
    return std::get<Error>(clips.error());
  }

  const auto thickness =
    kdl::str_to_int(propertyOrEmpty(container, RoomKeys::WallThickness));
  if (!thickness || *thickness <= 0)
  {
    return Error{
      fmt::format("Room '{}' has an invalid wall thickness", container.name())};
  }

  return RoomRecipe{
    std::move(spaces.value()),
    std::move(doors.value()),
    std::move(clips.value()),
    *thickness,
    propertyOrEmpty(container, RoomKeys::Floor) != "0",
    propertyOrEmpty(container, RoomKeys::Ceiling) != "0",
    propertyOrEmpty(container, RoomKeys::WallMaterial),
    propertyOrEmpty(container, RoomKeys::FloorMaterial),
    propertyOrEmpty(container, RoomKeys::CeilingMaterial),
    propertyOrEmpty(container, RoomKeys::Lights) == "1",
    kdl::str_to_int(propertyOrEmpty(container, RoomKeys::LightSpacing)).value_or(256),
    propertyOrEmpty(container, RoomKeys::AutoDoors) == "1",
    kdl::str_to_int(propertyOrEmpty(container, RoomKeys::DoorWidth)).value_or(64),
    kdl::str_to_int(propertyOrEmpty(container, RoomKeys::DoorHeight)).value_or(112),
  };
}

template <typename Container>
void setOrRemoveBoxes(
  Container& container, const std::string& key, const std::vector<vm::bbox3d>& boxes)
{
  if (boxes.empty())
  {
    container.removeProperty(key);
  }
  else
  {
    container.setProperty(key, formatBoxes(boxes));
  }
}

template <typename Container>
void writeRecipeTo(Container& container, const RoomRecipe& recipe)
{
  container.setProperty(RoomKeys::Version, CurrentVersion);
  container.setProperty(RoomKeys::Spaces, formatBoxes(recipe.spaces));
  setOrRemoveBoxes(container, RoomKeys::Doors, recipe.doors);
  setOrRemoveBoxes(container, RoomKeys::Clips, recipe.clips);
  container.setProperty(RoomKeys::WallThickness, std::to_string(recipe.wallThickness));
  container.setProperty(RoomKeys::Floor, recipe.generateFloor ? "1" : "0");
  container.setProperty(RoomKeys::Ceiling, recipe.generateCeiling ? "1" : "0");
  container.setProperty(RoomKeys::WallMaterial, recipe.wallMaterial);
  container.setProperty(RoomKeys::FloorMaterial, recipe.floorMaterial);
  container.setProperty(RoomKeys::CeilingMaterial, recipe.ceilingMaterial);
  container.setProperty(RoomKeys::Lights, recipe.generateLights ? "1" : "0");
  container.setProperty(RoomKeys::LightSpacing, std::to_string(recipe.lightSpacing));
  container.setProperty(RoomKeys::AutoDoors, recipe.autoDoors ? "1" : "0");
  container.setProperty(RoomKeys::DoorWidth, std::to_string(recipe.doorWidth));
  container.setProperty(RoomKeys::DoorHeight, std::to_string(recipe.doorHeight));
}

