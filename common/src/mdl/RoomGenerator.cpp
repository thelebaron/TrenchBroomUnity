Result<RoomFootprint> roomWorldFootprint(const GroupNode& room)
{
  auto recipe = readRoomRecipe(room.group());
  if (recipe.is_error())
  {
    return std::get<Error>(recipe.error());
  }

  const auto& transformation = room.group().transformation();
  if (!preservesAxes(transformation))
  {
    return Error{fmt::format(
      "Room '{}' is rotated by an angle that is not a multiple of 90 degrees",
      room.name())};
  }

  auto footprint = RoomFootprint{};
  footprint.wallThickness = static_cast<double>(recipe.value().wallThickness);
  footprint.generateFloor = recipe.value().generateFloor;
  footprint.generateCeiling = recipe.value().generateCeiling;
  for (const auto& space : recipe.value().spaces)
  {
    footprint.spaces.push_back(space.transform(transformation));
  }
  return footprint;
}

Result<CorridorPlan> planCorridor(
  const RoomFootprint& a, const RoomFootprint& b, const CorridorOptions& options)
{
  if (options.width <= 0.0 || options.height <= 0.0 || options.wallThickness <= 0.0)
  {
    return Error{"Corridor width, height and wall thickness must be positive"};
  }

  for (const auto& sa : a.spaces)
  {
    for (const auto& sb : b.spaces)
    {
      if (overlaps(shellOf(sa, a), sb) || overlaps(shellOf(sb, b), sa))
      {
        return Error{
          "The rooms overlap. To join them, extend one room with the other's space "
          "instead"};
      }
    }
  }

  auto straight = std::optional<CorridorCandidate>{};
  auto bent = std::optional<CorridorCandidate>{};
  const auto consider = [&](auto& best, auto candidate) {
    if (
      candidate && finishCorridorPlan(candidate->plan, a, b, options)
      && (!best || candidate->length < best->length))
    {
      best = std::move(candidate);
    }
  };

  for (const auto& sa : a.spaces)
  {
    for (const auto& sb : b.spaces)
    {
      // The corridor runs at the higher floor and must fit below both ceilings.
      const auto z0 = std::max(sa.min.z(), sb.min.z());
      const auto z1 = std::min(z0 + options.height, std::min(sa.max.z(), sb.max.z()));
      if (z1 - z0 < MinCorridorHeight)
      {
        continue;
      }

      for (const auto axis : {size_t{0}, size_t{1}})
      {
        consider(straight, planStraightCorridor(sa, a, sb, b, axis, z0, z1, options));
        for (const auto sideA : {-1, 1})
        {
          for (const auto sideB : {-1, 1})
          {
            consider(
              bent, planLCorridor(sa, a, sb, b, axis, sideA, sideB, z0, z1, options));
          }
        }
      }
    }
  }

  if (straight)
  {
    return std::move(straight->plan);
  }
  if (bent)
  {
    return std::move(bent->plan);
  }
  return Error{fmt::format(
    "Could not fit a corridor {} units wide between the rooms. Their floor heights must "
    "overlap, and there must be room for a straight or L-shaped corridor that doesn't "
    "pass through either room",
    options.width)};
}

Result<GroupNode*> connectRooms(
  Map& map,
  GroupNode& a,
  GroupNode& b,
  const RoomRecipe& corridorStyle,
  const CorridorOptions& options,
  const ModifiedRoomBrushes modifiedBrushes,
  const RoomLightOptions& lightOptions)
{
  if (&a == &b)
  {
    return Error{"Select two different rooms to connect"};
  }

  auto corridorOptions = options;
  corridorOptions.wallThickness = static_cast<double>(corridorStyle.wallThickness);
  corridorOptions.generateFloor = corridorStyle.generateFloor;
  corridorOptions.generateCeiling = corridorStyle.generateCeiling;

  auto footprintA = roomWorldFootprint(a);
  if (footprintA.is_error())
  {
    return std::get<Error>(footprintA.error());
  }
  auto footprintB = roomWorldFootprint(b);
  if (footprintB.is_error())
  {
    return std::get<Error>(footprintB.error());
  }

  auto plan = planCorridor(footprintA.value(), footprintB.value(), corridorOptions);
  if (plan.is_error())
  {
    return std::get<Error>(plan.error());
  }

  auto recipeA = readRoomRecipe(a.group());
  auto recipeB = readRoomRecipe(b.group());
  auto doorA = roomLocalBounds(a, plan.value().doorA);
  auto doorB = roomLocalBounds(b, plan.value().doorB);
  if (recipeA.is_error() || recipeB.is_error() || doorA.is_error() || doorB.is_error())
  {
    return Error{"Could not read the rooms to connect"};
  }

  auto newRecipeA = std::move(recipeA).value();
  auto newRecipeB = std::move(recipeB).value();
  newRecipeA.doors.push_back(doorA.value());
  newRecipeB.doors.push_back(doorB.value());

  auto transaction = Transaction{map, "Connect Rooms"};

  for (auto [room, recipe] : {std::pair{&a, &newRecipeA}, std::pair{&b, &newRecipeB}})
  {
    if (
      auto result = rebuildRoom(map, *room, *recipe, modifiedBrushes, lightOptions);
      result.is_error())
    {
      transaction.cancel();
      return std::get<Error>(result.error());
    }
  }

  GroupNode* corridor = nullptr;
  if (!plan.value().spaces.empty())
  {
    auto corridorRecipe = corridorStyle;
    corridorRecipe.spaces = plan.value().spaces;
    corridorRecipe.clips = plan.value().clips;
    corridorRecipe.doors.clear();

    auto result = createRoom(map, a.parent(), corridorRecipe, lightOptions, "Corridor");
    if (result.is_error())
    {
      transaction.cancel();
      return std::get<Error>(result.error());
    }
    corridor = result.value();
  }

  if (!transaction.commit())
  {
    return Error{"Could not commit room connection"};
  }
  return corridor;
}

