/** Whether the transformation maps axis-aligned boxes to axis-aligned boxes. */
bool preservesAxes(const vm::mat4x4d& transformation)
{
  for (size_t row = 0; row < 3; ++row)
  {
    auto nonZero = 0;
    for (size_t col = 0; col < 3; ++col)
    {
      const auto value = std::abs(transformation[col][row]);
      if (value > Epsilon)
      {
        if (std::abs(value - 1.0) > Epsilon)
        {
          return false;
        }
        ++nonZero;
      }
    }
    if (nonZero != 1)
    {
      return false;
    }
  }
  return true;
}

const std::string& materialFor(const RoomRecipe& recipe, const RoomSurface surface)
{
  switch (surface)
  {
  case RoomSurface::Floor:
    return recipe.floorMaterial;
  case RoomSurface::Ceiling:
    return recipe.ceilingMaterial;
  case RoomSurface::Wall:
    break;
  }
  return recipe.wallMaterial;
}

Result<std::vector<std::pair<Brush, RoomSurface>>> buildSurfaceBrushesImpl(
  const Map& map, const RoomRecipe& recipe, const vm::mat4x4d& transformation)
{
  auto shellResult = buildRoomShell(recipe);
  if (shellResult.is_error())
  {
    return std::get<Error>(shellResult.error());
  }

  const auto builder = BrushBuilder{
    map.world()->mapFormat(),
    map.worldBounds(),
    map.game()->config().faceAttribsConfig.defaults};
  const auto axisAligned = preservesAxes(transformation);

  auto result = std::vector<std::pair<Brush, RoomSurface>>{};
  for (const auto& shellBrush : shellResult.value())
  {
    const auto& material = materialFor(recipe, shellBrush.surface);
    const auto bounds =
      axisAligned ? shellBrush.bounds.transform(transformation) : shellBrush.bounds;

    auto brushResult = builder.createCuboid(bounds, material);
    if (brushResult.is_error())
    {
      return std::get<Error>(brushResult.error());
    }

    auto brush = std::move(brushResult.value());
    if (!axisAligned)
    {
      if (
        auto transformResult = brush.transform(map.worldBounds(), transformation, false);
        transformResult.is_error())
      {
        return std::get<Error>(transformResult.error());
      }
    }
    result.emplace_back(std::move(brush), shellBrush.surface);
  }
  return result;
}

Result<std::vector<Brush>> buildBrushesImpl(
  const Map& map, const RoomRecipe& recipe, const vm::mat4x4d& transformation)
{
  auto brushes = buildSurfaceBrushesImpl(map, recipe, transformation);
  if (brushes.is_error())
  {
    return std::get<Error>(brushes.error());
  }

  auto result = std::vector<Brush>{};
  result.reserve(brushes.value().size());
  for (auto& [brush, surface] : brushes.value())
  {
    result.push_back(std::move(brush));
  }
  return result;
}

bool brushMatches(const Brush& actual, const Brush& expected)
{
  if (
    actual.faceCount() != expected.faceCount()
    || !vm::is_equal(actual.bounds(), expected.bounds(), BrushMatchEpsilon))
  {
    return false;
  }

  const auto& material = expected.faces().front().attributes().materialName();
  return std::ranges::all_of(actual.faces(), [&](const auto& face) {
    return face.attributes().materialName() == material;
  });
}

/**
 * Splits the room's brush children into those that match the given expected brushes and
 * those that don't. Each expected brush matches at most one child.
 */
std::pair<std::vector<BrushNode*>, std::vector<BrushNode*>> matchRoomBrushes(
  const GroupNode& room, const std::vector<Brush>& expected)
{
  auto used = std::vector<bool>(expected.size(), false);
  auto matched = std::vector<BrushNode*>{};
  auto unmatched = std::vector<BrushNode*>{};

  for (auto* child : room.children())
  {
    auto* brushNode = dynamic_cast<BrushNode*>(child);
    if (brushNode == nullptr)
    {
      continue;
    }

    auto found = false;
    for (size_t i = 0; i < expected.size(); ++i)
    {
      if (!used[i] && brushMatches(brushNode->brush(), expected[i]))
      {
        used[i] = true;
        found = true;
        break;
      }
    }
    (found ? matched : unmatched).push_back(brushNode);
  }

  return {std::move(matched), std::move(unmatched)};
}

std::vector<Brush> expectedRoomBrushes(const Map& map, const GroupNode& room)
{
  auto recipe = readRoomRecipe(room.group());
  if (recipe.is_error())
  {
    return {};
  }

  auto brushes = buildBrushesImpl(map, recipe.value(), room.group().transformation());
  return brushes.is_success() ? std::move(brushes.value()) : std::vector<Brush>{};
}

/** Whether the two boxes share some volume (touching faces don't count). */
bool overlaps(const vm::bbox3d& lhs, const vm::bbox3d& rhs)
{
  for (size_t i = 0; i < 3; ++i)
  {
    if (lhs.min[i] >= rhs.max[i] - Epsilon || rhs.min[i] >= lhs.max[i] - Epsilon)
    {
      return false;
    }
  }
  return true;
}

bool isGeneratedLight(const Node* node)
{
  const auto* entityNode = dynamic_cast<const EntityNode*>(node);
  return entityNode != nullptr
         && entityNode->entity().property(RoomKeys::GeneratedLight) != nullptr;
}

std::vector<Node*> createLightNodes(
  const RoomRecipe& recipe,
  const vm::mat4x4d& transformation,
  const RoomLightOptions& options)
{
  auto result = std::vector<Node*>{};
  if (!recipe.generateLights)
  {
    return result;
  }

  for (const auto& light : planRoomLights(recipe))
  {
    const auto position = transformation * light.position;
    auto entity = Entity{{
      {EntityPropertyKeys::Classname, "light_unity"},
      {EntityPropertyKeys::Origin,
       fmt::format("{} {} {}", position.x(), position.y(), position.z())},
      {"intensity", fmt::format("{}", options.intensity)},
      {"range", fmt::format("{:.2f}", light.range * options.unitScale)},
      {RoomKeys::GeneratedLight, "1"},
    }};
    result.push_back(new EntityNode{std::move(entity)});
  }
  return result;
}

std::vector<Node*> toBrushNodes(std::vector<Brush> brushes)
{
  auto result = std::vector<Node*>{};
  result.reserve(brushes.size());
  for (auto& brush : brushes)
  {
    result.push_back(new BrushNode{std::move(brush)});
  }
  return result;
}

/** Creates a box from ranges along the horizontal axes a and o and the Z axis. */
vm::bbox3d makeBox(
  const size_t a,
  const double a0,
  const double a1,
  const size_t o,
  const double o0,
  const double o1,
  const double z0,
  const double z1)
{
  auto min = vm::vec3d{0, 0, z0};
  auto max = vm::vec3d{0, 0, z1};
  min[a] = a0;
  max[a] = a1;
  min[o] = o0;
  max[o] = o1;
  return {min, max};
}

struct AutoConnections
{
  /** Walls inserted between touching spaces, carved out of the later space. */
  std::vector<vm::bbox3d> partitions;
  /** Doorways through the walls between neighbouring spaces. */
  std::vector<vm::bbox3d> doors;
};

/**
 * Finds neighbouring spaces for RoomRecipe::autoDoors. Two spaces are neighbours if they
 * don't overlap, face each other along X or Y with a gap of at most two wall
 * thicknesses, and share some stretch of wall and some height.
 */
AutoConnections computeAutoConnections(const RoomRecipe& recipe)
{
  auto result = AutoConnections{};
  if (!recipe.autoDoors)
  {
    return result;
  }

  const auto thickness = static_cast<double>(recipe.wallThickness);
  const auto width = static_cast<double>(recipe.doorWidth);
  const auto height = static_cast<double>(recipe.doorHeight);
  const auto& spaces = recipe.spaces;

  for (size_t j = 1; j < spaces.size(); ++j)
  {
    for (size_t i = 0; i < j; ++i)
    {
      const auto& earlier = spaces[i];
      const auto& later = spaces[j];
      if (overlaps(earlier, later))
      {
        continue;
      }

      const auto zLo = std::max(earlier.min.z(), later.min.z());
      const auto zHi = std::min(earlier.max.z(), later.max.z());
      if (zHi - zLo <= Epsilon)
      {
        continue;
      }

      for (const auto axis : {size_t{0}, size_t{1}})
      {
        const auto other = 1u - axis;
        const auto earlierFirst = earlier.max[axis] <= later.min[axis] + Epsilon;
        const auto laterFirst = later.max[axis] <= earlier.min[axis] + Epsilon;
        if (!earlierFirst && !laterFirst)
        {
          continue;
        }

        const auto& lo = earlierFirst ? earlier : later;
        const auto& hi = earlierFirst ? later : earlier;
        const auto gap = hi.min[axis] - lo.max[axis];
        if (gap > 2.0 * thickness + Epsilon)
        {
          continue;
        }

        const auto oLo = std::max(earlier.min[other], later.min[other]);
        const auto oHi = std::min(earlier.max[other], later.max[other]);
        if (oHi - oLo <= Epsilon)
        {
          continue;
        }

        // The wall between the spaces spans [wallLo, wallHi] along the axis.
        auto wallLo = lo.max[axis];
        auto wallHi = hi.min[axis];
        if (gap <= Epsilon)
        {
          // The spaces touch, so there is no wall yet: carve one out of the later space.
          if (earlierFirst)
          {
            wallHi += thickness;
          }
          else
          {
            wallLo -= thickness;
          }
          result.partitions.push_back(
            makeBox(axis, wallLo, wallHi, other, oLo, oHi, zLo, zHi));
        }

        if (oHi - oLo >= width - Epsilon && zHi - zLo >= std::min(height, 32.0))
        {
          const auto centered = std::round(((oLo + oHi - width) / 2.0) / 8.0) * 8.0;
          const auto doorLo = std::clamp(centered, oLo, oHi - width);
          result.doors.push_back(makeBox(
            axis,
            wallLo - thickness,
            wallHi + thickness,
            other,
            doorLo,
            doorLo + width,
            zLo,
            std::min(zLo + height, zHi)));
        }
      }
    }
  }
  return result;
}

