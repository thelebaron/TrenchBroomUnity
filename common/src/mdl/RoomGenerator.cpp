std::vector<RoomLight> planRoomLights(const RoomRecipe& recipe)
{
  const auto spacing = std::max(32.0, static_cast<double>(recipe.lightSpacing));

  auto result = std::vector<RoomLight>{};
  for (const auto& space : recipe.spaces)
  {
    const auto size = space.size();
    const auto countX = std::max(1L, std::lround(size.x() / spacing));
    const auto countY = std::max(1L, std::lround(size.y() / spacing));
    const auto z = space.max.z() - std::min(16.0, size.z() / 4.0);
    const auto range = std::max(spacing, size.z()) * 1.5;

    for (long i = 0; i < countX; ++i)
    {
      for (long j = 0; j < countY; ++j)
      {
        const auto position = vm::vec3d{
          space.min.x()
            + (static_cast<double>(i) + 0.5) * size.x() / static_cast<double>(countX),
          space.min.y()
            + (static_cast<double>(j) + 0.5) * size.y() / static_cast<double>(countY),
          z};

        // Overlapping spaces would otherwise place lights on top of each other.
        const auto tooClose = std::ranges::any_of(result, [&](const auto& light) {
          return vm::distance(light.position, position) < spacing * 0.5;
        });
        if (!tooClose)
        {
          result.push_back({position, range});
        }
      }
    }
  }
  return result;
}

