/** The lowest opening a corridor may have where the two rooms' heights overlap. */
constexpr auto MinCorridorHeight = 32.0;

struct CorridorCandidate
{
  CorridorPlan plan;
  double length;
};

/**
 * Picks a grid aligned value in [lo, hi] that is closest to target, or nothing if the
 * range contains no grid aligned value.
 */
std::optional<double> pickGridValue(
  const double lo, const double hi, const double target, const double gridSize)
{
  const auto grid = gridSize > 0.0 ? gridSize : 1.0;
  const auto first = std::ceil(lo / grid - Epsilon) * grid;
  const auto last = std::floor(hi / grid + Epsilon) * grid;
  if (first > last + Epsilon)
  {
    return std::nullopt;
  }
  return std::clamp(std::round(target / grid) * grid, first, last);
}


vm::bbox3d dilate(
  const vm::bbox3d& space,
  const double thickness,
  const bool generateFloor,
  const bool generateCeiling)
{
  return {
    space.min - vm::vec3d{thickness, thickness, generateFloor ? thickness : 0.0},
    space.max + vm::vec3d{thickness, thickness, generateCeiling ? thickness : 0.0}};
}

vm::bbox3d shellOf(const vm::bbox3d& space, const RoomFootprint& room)
{
  return dilate(space, room.wallThickness, room.generateFloor, room.generateCeiling);
}

/** A door box that reaches through the wall whose inner face is at the given value. */
std::pair<double, double> doorRange(const double face, const double thickness)
{
  return {face - thickness, face + thickness};
}

/** A straight corridor running along axis a from space sa of room A to sb of B. */
std::optional<CorridorCandidate> planStraightCorridor(
  const vm::bbox3d& sa,
  const RoomFootprint& a,
  const vm::bbox3d& sb,
  const RoomFootprint& b,
  const size_t axis,
  const double z0,
  const double z1,
  const CorridorOptions& options)
{
  const auto other = 1u - axis;
  const auto width = options.width;

  const auto lo = std::max(sa.min[other], sb.min[other]);
  const auto hi = std::min(sa.max[other], sb.max[other]) - width;
  const auto c0 = pickGridValue(lo, hi, (lo + hi) / 2.0, options.gridSize);
  if (!c0)
  {
    return std::nullopt;
  }

  auto start = 0.0;
  auto end = 0.0;
  auto faceA = 0.0;
  auto faceB = 0.0;
  if (sb.min[axis] >= sa.max[axis])
  {
    faceA = sa.max[axis];
    faceB = sb.min[axis];
    start = faceA + a.wallThickness;
    end = faceB - b.wallThickness;
  }
  else if (sa.min[axis] >= sb.max[axis])
  {
    faceA = sa.min[axis];
    faceB = sb.max[axis];
    start = faceB + b.wallThickness;
    end = faceA - a.wallThickness;
  }
  else
  {
    return std::nullopt;
  }

  if (end < start - Epsilon)
  {
    // The walls overlap.
    return std::nullopt;
  }

  auto plan = CorridorPlan{};
  if (end - start > Epsilon)
  {
    plan.spaces.push_back(makeBox(axis, start, end, other, *c0, *c0 + width, z0, z1));
  }

  const auto [a0, a1] = doorRange(faceA, a.wallThickness);
  const auto [b0, b1] = doorRange(faceB, b.wallThickness);
  plan.doorA = makeBox(axis, a0, a1, other, *c0, *c0 + width, z0, z1);
  plan.doorB = makeBox(axis, b0, b1, other, *c0, *c0 + width, z0, z1);
  return CorridorCandidate{std::move(plan), std::max(0.0, end - start)};
}

/**
 * An L-shaped corridor that leaves room A along axis a (towards sideA) and enters room B
 * along the other horizontal axis (towards sideB).
 */
std::optional<CorridorCandidate> planLCorridor(
  const vm::bbox3d& sa,
  const RoomFootprint& a,
  const vm::bbox3d& sb,
  const RoomFootprint& b,
  const size_t axis,
  const int sideA,
  const int sideB,
  const double z0,
  const double z1,
  const CorridorOptions& options)
{
  const auto other = 1u - axis;
  const auto width = options.width;
  const auto tA = a.wallThickness;
  const auto tB = b.wallThickness;
  const auto tC = options.wallThickness;

  // The second leg runs along the other axis at [m, m + width] on this axis. It must
  // lie within B and clear A's shell.
  const auto mLo =
    sideA > 0 ? std::max(sb.min[axis], sa.max[axis] + tA + tC) : sb.min[axis];
  const auto mHi = sideA > 0 ? sb.max[axis] - width
                             : std::min(sb.max[axis], sa.min[axis] - tA - tC) - width;
  const auto m = pickGridValue(mLo, mHi, sideA > 0 ? mLo : mHi, options.gridSize);

  // The first leg runs along this axis at [n, n + width] on the other axis. It must lie
  // within A and clear B's shell.
  const auto nLo =
    sideB > 0 ? sa.min[other] : std::max(sa.min[other], sb.max[other] + tB + tC);
  const auto nHi = sideB > 0 ? std::min(sa.max[other], sb.min[other] - tB - tC) - width
                             : sa.max[other] - width;
  const auto n = pickGridValue(nLo, nHi, sideB > 0 ? nHi : nLo, options.gridSize);

  if (!m || !n)
  {
    return std::nullopt;
  }

  const auto faceA = sideA > 0 ? sa.max[axis] : sa.min[axis];
  const auto faceB = sideB > 0 ? sb.min[other] : sb.max[other];

  const auto leg1Start = sideA > 0 ? faceA + tA : *m;
  const auto leg1End = sideA > 0 ? *m + width : faceA - tA;
  const auto leg2Start = sideB > 0 ? *n : faceB + tB;
  const auto leg2End = sideB > 0 ? faceB - tB : *n + width;
  if (leg1End - leg1Start <= Epsilon || leg2End - leg2Start <= Epsilon)
  {
    return std::nullopt;
  }

  auto plan = CorridorPlan{};
  plan.spaces.push_back(makeBox(axis, leg1Start, leg1End, other, *n, *n + width, z0, z1));
  plan.spaces.push_back(makeBox(axis, *m, *m + width, other, leg2Start, leg2End, z0, z1));

  const auto [a0, a1] = doorRange(faceA, tA);
  const auto [b0, b1] = doorRange(faceB, tB);
  plan.doorA = makeBox(axis, a0, a1, other, *n, *n + width, z0, z1);
  plan.doorB = makeBox(other, b0, b1, axis, *m, *m + width, z0, z1);

  return CorridorCandidate{
    std::move(plan), (leg1End - leg1Start) + (leg2End - leg2Start)};
}

/**
 * Checks that the corridor doesn't pass through either room and computes the clips
 * where its shell overlaps the rooms' walls.
 */
bool finishCorridorPlan(
  CorridorPlan& plan,
  const RoomFootprint& a,
  const RoomFootprint& b,
  const CorridorOptions& options)
{
  for (const auto& corridorSpace : plan.spaces)
  {
    const auto corridorShell = dilate(
      corridorSpace,
      options.wallThickness,
      options.generateFloor,
      options.generateCeiling);

    for (const auto* room : {&a, &b})
    {
      for (const auto& space : room->spaces)
      {
        const auto shell = shellOf(space, *room);
        if (overlaps(corridorSpace, shell) || overlaps(corridorShell, space))
        {
          return false;
        }
        if (const auto clip = intersection(corridorShell, shell))
        {
          plan.clips.push_back(*clip);
        }
      }
    }
  }
  return true;
}

